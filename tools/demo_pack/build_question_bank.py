#!/usr/bin/env python3
r"""Builds ASK_QUESTION_BANK.md from the question corpora that already have independent answer keys.

    python -X utf8 tools/demo_pack/build_question_bank.py [--out C:\NexusAI-DemoPack\ASK_QUESTION_BANK.md]

The output goes OUTSIDE the repository by default, on purpose: the corpora hold identifiers of the demo case that the repository's real-data scanner treats as
real-looking, so the generated bank is not committed; only this generator is.

Sources: evaluation/golden_questions_v2.json (62 questions), holdout_questions_v1.json (13) and holdout_media_v1.json (28), each question with the answer an independent SQL
count or an inspected file gave when the corpus was written. The bank groups them by case and family, in the order a demonstration should use, and adds the questions
that need no real value (templates for a real-data demonstration, filled in locally). It reads no real file.
"""
import argparse
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

FAMILY_TITLES = {
    "cdr": "Call records (CDR)", "ipdr": "Internet sessions (IPDR)", "anpr": "Vehicle sightings (ANPR)", "access_log": "Access logs", "subscriber": "Subscribers",
    "tower": "Cell towers", "transaction": "Transactions", "cross": "Across families", "negative": "Things it must not answer",
    "document": "Documents", "image": "Images", "audio": "Audio", "video": "Video",
    "anpr_model_observation": "Plate reads from images", "video_anpr_plate_group": "Plates tracked in video", "image_ocr_observation": "Text read from images (OCR)",
    "audio_timestamp_segment": "Audio segments", "face_model_observation": "Face detections", "image_fingerprint_observation": "Image fingerprints",
}
FAMILY_ORDER = ["cdr", "ipdr", "anpr", "access_log", "subscriber", "tower", "transaction", "cross", "negative", "document", "image", "audio", "video",
                "anpr_model_observation", "video_anpr_plate_group", "image_ocr_observation", "audio_timestamp_segment", "face_model_observation", "image_fingerprint_observation", "anpr"]


def expected_text(q):
    e = q.get("expect")
    check = q.get("check")
    if check == "number":
        return "the number %s" % (e,)
    if check == "top":
        return "first-ranked: %s" % (e,)
    if check == "contains":
        return "the answer shows: %s" % ", ".join(str(x) for x in e)
    if check == "empty":
        return "no matches, not unrelated rows"
    if check == "unsupported":
        return "no confident answer (a clarification, nothing found, or unsupported)"
    if check == "clarify":
        return "asks for what is missing"
    return "manual review"


def load():
    out = []
    for name in ("golden_questions_v2", "holdout_questions_v1", "holdout_media_v1"):
        with open(os.path.join(REPO, "evaluation", name + ".json"), encoding="utf-8") as handle:
            data = json.load(handle)
        collections = data["collections"]
        for q in data["questions"]:
            out.append(dict(q, source=name, collection=collections[q["c"]] if q["c"] in collections else collections[sorted(collections)[0]]))
    return out


def table(rows):
    lines = ["| ID | Question | Expected | Note |", "|---|---|---|---|"]
    for q in rows:
        note = (q.get("note") or "").replace("|", "/").replace("\n", " ")
        if len(note) > 140:
            note = note[:137] + "..."
        lines.append("| %s | %s | %s | %s |" % (q["id"], q["q"].replace("|", "/"), expected_text(q).replace("|", "/"), note))
    return lines


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=os.path.join("C:\\", "NexusAI-DemoPack", "ASK_QUESTION_BANK.md"))
    args = parser.parse_args(argv)
    questions = load()
    by_case = {}
    for q in questions:
        by_case.setdefault(q["collection"], []).append(q)

    lines = [
        "# Ask question bank for the cases in the application", "",
        "Generated by `tools/demo_pack/build_question_bank.py` from the question corpora that carry independent answer keys (%d questions). "
        "Every expected value was checked against the data when the corpus was written (an SQL count over the raw rows, or an inspected file); re-check against the live case before a "
        "demonstration, because the case data can change (`factory.py explain` shows an answer next to its key)." % len(questions), "",
        "## How to ask", "",
        "- In the workspace at http://localhost:4181: open the case, **Ask this case**, type the question.",
        "- From PowerShell, with the SQL and the checks shown: `. .\\evaluation\\question_factory\\Run-Arms.ps1; $script:AskedSecrets['LOCALAI_API_KEY'] = $true; "
        "Ask-Case -Collection <collection> \"<question>\"`.",
        "- To generate more questions with keys for a case: `New-QuestionSet -Seed N -Name f.json -Collection <collection>` (about 249 structured questions, then `--per-intent 1` for 79).", "",
        "## Order and cautions for a live demonstration", "",
        "1. **Warm the model first** (ask four or five questions per case before the audience arrives); the first question after a restart can take minutes, a warm one 9 to 20 s.",
        "2. **Ask by family**, one family after another: mixed-family sequences were slower in rehearsal.",
        "3. Start with counts and identifier filters (they were answered in every recent run), then time of day, then rankings, then the honest absences and abstentions.",
        "4. Avoid, or say beforehand that it is a known gap: *how many images are in this case?* (withheld, no inventory view), *which document mentions ...* for access-style words (DOC-05), "
        "*still need manual review* (M3, M12) and *distinct values of a field* (M11, M14) which are asked back, month-against-month questions (the multimodal case has call records for April only; "
        "when the lane declines the older path can take minutes), and names of people (abstained, by design).", "",
    ]
    case_order = ["nexusai-forensic-demo", "nexusai-multimodal-product-acceptance"]
    descriptions = {
        "nexusai-forensic-demo": "The demo case: call records, internet sessions, vehicle sightings, access logs, subscribers, towers, transactions (the identifiers look synthetic; confirm before showing).",
        "nexusai-multimodal-product-acceptance": "The main working case: structured records plus documents, images, audio, video, plate images and faces.",
    }
    for collection in case_order:
        rows = by_case.get(collection, [])
        if not rows:
            continue
        lines += ["## Case `%s`" % collection, "", descriptions.get(collection, ""), "", "%d questions." % len(rows), ""]
        for fam in FAMILY_ORDER:
            fam_rows = [q for q in rows if q["family"] == fam]
            if not fam_rows:
                continue
            lines += ["### %s" % FAMILY_TITLES.get(fam, fam), ""] + table(fam_rows) + [""]
        rest = sorted({q["family"] for q in rows} - set(FAMILY_ORDER))
        for fam in rest:
            lines += ["### %s" % FAMILY_TITLES.get(fam, fam), ""] + table([q for q in rows if q["family"] == fam]) + [""]

    lines += [
        "## Link-analysis questions on the generated demo case", "",
        "The generated case (`tools/demo_pack/build_demo_pack.py`) carries planted connections with the answer key, so connection questions have known answers. "
        "Its questions are in the pack's `DEMO_QUESTIONS.md`: contact profile, common contacts, co-location, tower dump, possible meeting, device and SIM change, successor number, movement, "
        "rhythm change and address attribution. They are the targets of the Ask engine (roadmap 6.8); today the product answers the counts and filters of its first tier.", "",
        "## A real-data demonstration: questions with no real value in them", "",
        "These are written with placeholders so the document holds nothing real. Fill them in locally from the owner's own files (the subscriber number is in the file name or the first rows; "
        "the expected counts come from `tools/real_data/profile_structure.py --mode local` and `reconcile_aggregates.py`, which print counts, never rows), "
        "after the use of the real files for a demonstration has been recorded in the vault's authority register (`docs/data/real-data-handling-policy.md`).", "",
        "| Family | Question template | Expected (from the local profile) |", "|---|---|---|",
        "| Call records | How many call records are there where the phone number is `<subscriber number>`? | rows of the file less exact repeats |",
        "| Call records | How many call records were there at night? | count by hour from the local profile, case clock |",
        "| Call records | Who does `<subscriber number>` talk to most? | the top counterparties from the local profile |",
        "| Call records | What is the earliest and the latest call time? | the time range from the local profile |",
        "| Call records | How many incoming versus outgoing calls are there? | the direction histogram |",
        "| Internet records | How many internet sessions are there for `<subscriber number>`? | rows of the IPDR file |",
        "| Internet records | Who held `<public address>` on port `<port>` at `<instant>`? | the holder(s) in the file; ambiguous is a valid answer |",
        "| Internet records | Which application was used most? | the application histogram |",
        "| Tower dump | Which numbers appear at two or more cells? | from the local aggregate; authority-gated |",
        "| Honest absence | How many calls does `<a number not in the files>` have? | no record contains it |", "",
    ]
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print("wrote %s (%d questions in %d cases)" % (args.out, len(questions), len(by_case)))
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main(sys.argv[1:]))
