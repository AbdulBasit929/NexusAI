README = """SYNTHETIC CASE - not evidence, not real data.
Every number, identifier, address and coordinate in these files comes from a reserved range (documentation addresses, the test
network code 00101, the test TAC prefix 00, the project number block 923000000000-923000099999, a fictional grid in open ocean).
Generated by tools/case_generator (version %s, specification %s). key/key.json holds the answers planted in the files.
Where a layout's meaning is still unconfirmed, key.json says which proposed meaning the files use (layout_assumptions).
"""


def reserved_imei14(n):
    return world_reserved.synthetic_imei(n)[:14]


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def dump_plan(world, operator):
    """The cells and the window of an operator's tower dump: the planted meeting cell first, then the subjects' work and home cells;
    the window starts on the day of the first planted co-location window of that operator, else on the third day of the case."""
    import datetime
    sites = []
    plants = [p for p in world.p3 if p["operator"] == operator]
    for plant in plants:
        sites.append(plant["meeting_site"])
    for p in world.persons:
        if p.role == "subject" and p.operator == operator:
            sites += [p.work_cell, p.home_cell]
    sites = list(dict.fromkeys(sites))[:3]
    if not sites:
        return None
    first = None
    for ev in world.events:
        if any(ev.plant and ev.plant.startswith(plant["id"] + ":w") for plant in plants):
            first = ev.start
            break
    day = (first or datetime.datetime.combine(datetime.date.fromisoformat(world.params.start_date) + datetime.timedelta(days=2), datetime.time(0, 0))).replace(hour=0, minute=0, second=0)
    return sorted(sites), day, day + datetime.timedelta(days=world.params.dump_days)


def build_case(params, registry=None):
    """Returns (world, renders {pid: RenderedFile}, key dict)."""
    registry = registry or load_registry()
    world = w.build_world(params)
    subjects = [p for p in world.persons if p.role == "subject"]
    renders = {}
    for subject in subjects:
        layout_id = w.OPERATOR_LAYOUTS[subject.operator]
        renders[subject.pid] = render.render_subject(world, registry.get(layout_id), subject)
    visible = {s.msisdn: renders[s.pid].visible for s in subjects}
    threshold = params.resolved_hub_threshold()
    contacts = oracle.contacts_by_subject(visible)
    hubs = oracle.hub_numbers(contacts, threshold)
    by_pid = {p.pid: p for p in world.persons}
    plants = []
    for plant in world.p2:
        x, y = by_pid[plant["x"]], by_pid[plant["y"]]
        planted_shared = [{"person": s, "number": by_pid[s].msisdn, "x_count_planted": plant["counts"][s][x.pid], "y_count_planted": plant["counts"][s][y.pid]}
                          for s in plant["shared"]]
        service = next(d for d in plant["decoys"] if d["kind"] == "service_in_common")
        hub = next(d for d in plant["decoys"] if d["kind"] == "hub_in_common")
        hub_number = by_pid[hub["person"]].msisdn
        both_see_service = all(any(r["b_raw_label"] == service["number"] for r in visible[p.msisdn]) for p in (x, y))
        plants.append({
            "id": plant["id"], "type": "common_contacts", "x": {"person": x.pid, "msisdn": x.msisdn}, "y": {"person": y.pid, "msisdn": y.msisdn},
            "planted_shared": planted_shared,
            "decoys": [
                {"kind": "service_in_common", "number": service["number"], "visible_in_both_files": both_see_service, "must_be_excluded": True},
                {"kind": "hub_in_common", "number": hub_number, "subjects_in_contact": hubs.get(hub_number, 0), "hub_threshold": threshold,
                 "visible_in_both_files": hub_number in contacts[x.msisdn] and hub_number in contacts[y.msisdn], "must_be_excluded": True}]})
    planted_pair = {frozenset((p["x"]["msisdn"], p["y"]["msisdn"])): p["id"] for p in plants}
    a2 = []
    for i, x in enumerate(subjects):
        for y in subjects[i + 1:]:
            answer = oracle.a2_common(visible, x.msisdn, y.msisdn, threshold)
            answer["plant"] = planted_pair.get(frozenset((x.msisdn, y.msisdn)))
            a2.append(answer)
    # --- A5 co-location and plant P3 ---------------------------------------------------------------------------------------------
    row_of = {row["uid"]: (p.msisdn, row) for p in subjects for row in renders[p.pid].visible}
    by_tag = {}
    for ev in world.events:
        if ev.plant and ev.plant.startswith("P3-"):
            by_tag.setdefault(ev.plant, []).append(ev.uid)

    def natural(uid):
        msisdn, row = row_of[uid]
        return {"subject": msisdn, "start_local": row["start_local"], "cell_key": row["cell_key"]}
    decoy_kind = {"far_apart": "same_cell_far_apart_in_time", "just_outside": "same_cell_just_outside_window", "other_cell": "same_moment_different_cells"}
    for plant in world.p3:
        x, y = by_pid[plant["x"]], by_pid[plant["y"]]
        windows, decoys = [], []
        for tag in sorted(by_tag):
            if not tag.startswith(plant["id"] + ":"):
                continue
            events = [natural(uid) for uid in by_tag[tag]]
            times = sorted(e["start_local"] for e in events)
            if ":w" in tag:
                windows.append({"tag": tag, "cell_key": events[0]["cell_key"], "start_local": times[0], "end_local": times[-1], "events": events})
            elif tag.rsplit(":", 1)[1] in decoy_kind:
                decoys.append({"kind": decoy_kind[tag.rsplit(":", 1)[1]], "tag": tag, "events": events, "must_not_pair": True})
        plants.append({"id": plant["id"], "type": "colocation", "x": {"person": x.pid, "msisdn": x.msisdn}, "y": {"person": y.pid, "msisdn": y.msisdn},
                       "operator": w.OPERATOR_LABELS[plant["operator"]], "window_minutes": plant["window_minutes"],
                       "planted_windows": windows, "decoys": decoys})
    # --- plant P4 (possible meetings) --------------------------------------------------------------------------------------------------
    for plant in world.p3:
        windows_by_tag = {w_["tag"]: w_ for p_ in plants if p_["id"] == plant["id"] for w_ in p_["planted_windows"]}
        x, y = by_pid[plant["x"]], by_pid[plant["y"]]
        meetings, negatives = [], []
        for k in range(1, len(windows_by_tag) + 1):
            window = windows_by_tag.get("%s:w%d" % (plant["id"], k))
            if window is None:
                continue
            contact = [row_of[uid][1]["start_local"] for uid in by_tag.get("%s:m%d" % (plant["id"], k), [])]
            if k <= plant["meeting_windows"]:
                meetings.append({"window_tag": window["tag"], "window_start": window["start_local"], "contacts": sorted(set(contact))})
            elif k == plant["meeting_windows"] + 1:
                early = sorted({row_of[uid][1]["start_local"] for uid in by_tag.get("%s:early" % plant["id"], [])})
                negatives.append({"kind": "contact_too_early", "window_tag": window["tag"], "window_start": window["start_local"], "contacts": early})
            else:
                negatives.append({"kind": "co_location_without_contact", "window_tag": window["tag"], "window_start": window["start_local"], "contacts": []})
        alone = sorted({row_of[uid][1]["start_local"] for uid in by_tag.get("%s:d:contact_alone" % plant["id"], [])})
        if alone:
            negatives.append({"kind": "contact_without_co_location", "window_tag": None, "window_start": None, "contacts": alone})
        plants.append({"id": plant["id"].replace("P3", "P4"), "type": "possible_meeting", "pair": plant["id"], "x": {"person": x.pid, "msisdn": x.msisdn},
                       "y": {"person": y.pid, "msisdn": y.msisdn}, "gap_minutes": plant["contact_gap_minutes"], "planted_meetings": meetings, "negatives": negatives})
    p3_pair = {frozenset((p["x"]["msisdn"], p["y"]["msisdn"])): p["id"] for p in plants if p["type"] == "colocation"}
    a5, a7 = [], []
    for i, x in enumerate(subjects):
        for y in subjects[i + 1:]:
            if x.operator != y.operator:
                continue  # cell identities are per operator: two operators never share a cell key
            answer = oracle.a5_colocation(renders[x.pid].visible, renders[y.pid].visible, params.window_minutes)
            answer.update({"x": x.msisdn, "y": y.msisdn, "plant": p3_pair.get(frozenset((x.msisdn, y.msisdn)))})
            a5.append(answer)
            meetings_answer = oracle.a7_meetings(renders[x.pid].visible, renders[y.pid].visible, x.msisdn, y.msisdn, answer["windows"], params.contact_gap_minutes)
            meetings_answer.update({"x": x.msisdn, "y": y.msisdn, "plant": p3_pair.get(frozenset((x.msisdn, y.msisdn)))})
            a7.append(meetings_answer)
    # --- tower dumps and A6 ----------------------------------------------------------------------------------------------------------
    dumps, a6 = [], []
    if params.dumps:
        for op, op_label in enumerate(w.OPERATOR_LABELS):
            plan = dump_plan(world, op)
            if plan is None:
                continue
            sites, win_start, win_end = plan
            entry = registry.get(w.OPERATOR_DUMP_LAYOUTS[op])
            rendered = render.render_views(world, entry, render.dump_views(world, op, set(sites), win_start, win_end), label="dump-%s" % op_label)
            name = "dump-%s" % op_label
            renders[name] = rendered
            cell_keys = [render.site_cell_key(entry, op, s) for s in sites]
            dumps.append({"name": name, "operator": op_label, "layout_id": entry["layout_id"], "file": None, "sites": sites, "cell_keys": cell_keys,
                          "window_start": win_start.isoformat(sep=" "), "window_end": win_end.isoformat(sep=" "), "rows": len(rendered.rows),
                          "events_not_representable": len(rendered.skipped)})
            answer = oracle.a6_population(rendered.visible, cell_keys)
            answer["dump"] = name
            a6.append(answer)
    # --- internet-record exports and application usage ---------------------------------------------------------------------------------
    session_files, usage_files = [], []
    for s in subjects:
        entry = registry.get(w.OPERATOR_IPDR_LAYOUTS[s.operator])
        name = "ipdr-%s" % s.pid
        renders[name] = render_sessions.render_sessions(world, entry, [(x, s) for x in world.sessions if x.pid == s.pid], label=s.pid, damage=True)
        session_files.append({"name": name, "person": s.pid, "msisdn": s.msisdn, "layout_id": entry["layout_id"], "file": None, "rows": len(renders[name].rows)})
    for s in subjects[:params.app_usage_exports]:
        entry = registry.get(w.APP_USAGE_LAYOUT)
        name = "usage-%s" % s.pid
        renders[name] = render_sessions.render_app_usage(world, entry, s, [x for x in world.sessions if x.pid == s.pid])
        usage_files.append({"name": name, "person": s.pid, "msisdn": s.msisdn, "layout_id": entry["layout_id"], "file": None, "rows": len(renders[name].rows)})
    # --- plant P7 (address translation) and A13 ----------------------------------------------------------------------------------------
    ip_queries, a13 = [], []
    for plant in world.p7:
        entry = registry.get(w.OPERATOR_IPDR_LAYOUTS[plant["operator"]])
        items = [(s, by_pid[s.pid]) for s in world.sessions if s.plant and s.plant.startswith(plant["id"] + ":")]
        name = "ipquery-%s" % plant["id"]
        rendered = render_sessions.render_sessions(world, entry, items, label=name, preamble_values={
            "{ts_start}": plant["window_start"], "{ts_end}": plant["window_end"], "{public_ip}": plant["public_ip"]})
        renders[name] = rendered
        ip_queries.append({"name": name, "plant": plant["id"], "operator": w.OPERATOR_LABELS[plant["operator"]], "layout_id": entry["layout_id"], "file": None,
                           "public_ip": plant["public_ip"], "window_start": plant["window_start"], "window_end": plant["window_end"], "rows": len(rendered.rows)})
        seen = [{"public_ip": r["public_ip"], "port_from": r["public_port_from"], "port_to": r["public_port_to"],
                 "begin": r["nat_start_local"] or r["start_local"], "end": r["nat_end_local"] or r["end_local"], "msisdn": r["msisdn"]} for r in rendered.rows]
        probes = []
        for probe in plant["probes"]:
            answer = oracle.a13_holders(seen, plant["public_ip"], probe["port"], probe["instant"])
            probes.append({"label": probe["label"], "port": probe["port"], "instant": probe["instant"], "intent": probe["intent"],
                           "intended_holders": sorted(by_pid[pid].msisdn for pid in probe["intended_holders"]), "result": answer["result"], "holders": answer["holders"]})
            a13.append({"plant": plant["id"], "public_ip": plant["public_ip"], **probes[-1]})
        plants.append({"id": plant["id"], "type": "address_translation", "operator": w.OPERATOR_LABELS[plant["operator"]], "public_ip": plant["public_ip"],
                       "subscriptions": {pid: by_pid[pid].msisdn for pid in plant["subscriptions"]}, "probes": probes})
    # --- plant P5 (device and SIM changes) and A8 ---------------------------------------------------------------------------------------
    def device14(n):
        return reserved_imei14(n)
    for record in world.p5:
        if record["kind"] == "dual_sim":
            plants.append({"id": record["id"], "type": "dual_sim", "numbers": sorted(by_pid[pid].msisdn for pid in record["pids"]), "imei": device14(record["imei_n"])})
        else:
            plants.append({"id": record["id"], "type": "device_change", "kind": record["kind"], "number": by_pid[record["pid"]].msisdn, "from": record["from"],
                           "old_imsi": record["old_imsi"], "new_imsi": record["new_imsi"], "old_imei": device14(record["old_imei_n"]), "new_imei": device14(record["new_imei_n"])})
    a8 = oracle.a8_device_history({s.msisdn: renders[s.pid].visible for s in subjects})
    case_start = datetime.datetime.combine(datetime.date.fromisoformat(params.start_date), datetime.time(0, 0))
    case_end = case_start + datetime.timedelta(days=params.period_days)
    a9 = oracle.a9_successors({s.msisdn: renders[s.pid].visible for s in subjects}, case_start, case_end)
    for record in world.p6:
        if record["kind"] == "successor":
            plants.append({"id": record["id"], "type": "successor", "old": by_pid[record["old"]].msisdn, "new": by_pid[record["new"]].msisdn,
                           "last_day_old": (case_start + datetime.timedelta(days=record["last_day_old"])).strftime("%Y-%m-%d"),
                           "first_day_new": (case_start + datetime.timedelta(days=record["first_day_new"])).strftime("%Y-%m-%d"), "with_device": record["with_device"]})
        else:
            plants.append({"id": record["id"], "type": record["kind"], "number": by_pid[record["pid"]].msisdn})
    # --- plant P8 (movement and rhythm), A10 and A11 -----------------------------------------------------------------------------------
    visible_all = {s.msisdn: renders[s.pid].visible for s in subjects}
    a10 = oracle.a10_movement(visible_all, case_start)
    a11 = oracle.a11_rate_change(visible_all)
    p8_events = {}
    for ev in world.events:
        if ev.plant and ev.plant.startswith("P8-"):
            p8_events.setdefault(ev.plant, []).append(ev.uid)
    day_of = lambda n: (case_start + datetime.timedelta(days=n)).strftime("%Y-%m-%d")   # noqa: E731
    for record in world.p8:
        person = by_pid[record["pid"]]
        entry = registry.get(w.OPERATOR_LAYOUTS[person.operator])
        cell = lambda site: render.site_cell_key(entry, person.operator, site)   # noqa: E731
        base = {"id": record["id"], "type": record["kind"], "number": person.msisdn}
        if record["kind"] == "relocation":
            base.update({"from_day": record["from_day"], "from_date": day_of(record["from_day"]), "old_cell_key": cell(record["old_cell"]), "new_cell_key": cell(record["new_cell"])})
        elif record["kind"] in ("impossible_speed", "slow_decoy"):
            base.update({"day": day_of(record["day"]), "from_cell_key": cell(record["from_site"]), "to_cell_key": cell(record["to_site"]), "gap_s": record["gap_s"],
                         "events": [{"subject": person.msisdn, "start_local": row_of[uid][1]["start_local"], "cell_key": row_of[uid][1]["cell_key"]} for uid in p8_events[record["tag"]]]})
        elif record["kind"] == "rate_change":
            base.update({"from_day": record["from_day"], "from_date": day_of(record["from_day"]), "multiplier": record["multiplier"]})
        elif record["kind"] == "outlier_day":
            base.update({"day": day_of(record["day"]), "multiplier": record["multiplier"]})
        elif record["kind"] == "short_trip":
            base.update({"from_date": day_of(record["from_day"]), "to_date": day_of(record["to_day"]), "first_week": record["from_day"] // 7,
                         "home_cell_key": cell(record["home_cell"]), "trip_cell_key": cell(record["trip_cell"])})
        plants.append(base)
    key = {
        "case_id": None, "seed": params.seed, "generator_version": w.GENERATOR_VERSION, "spec_version": w.SPEC_VERSION,
        "clock": {"local_zone": w.LOCAL_ZONE, "utc_offset_hours": w.LOCAL_UTC_OFFSET_HOURS, "key_time": "local wall clock as the files show it"},
        "params": json.loads(json.dumps(params.__dict__)),
        "subjects": [{"person": s.pid, "msisdn": s.msisdn, "operator": w.OPERATOR_LABELS[s.operator], "layout_id": renders[s.pid].layout_id,
                      "file": None, "rows": len(renders[s.pid].rows), "events_not_representable": len(renders[s.pid].skipped)} for s in subjects],
        "dumps": dumps, "sessions": session_files, "app_usage": usage_files, "ip_queries": ip_queries,
        "structure": world.structure,
        "plants": plants,
        "oracle": {"parameters": {"hub_threshold": threshold, "contact_kinds": list(oracle.PERSON_KINDS), "window_minutes": params.window_minutes,
                              "contact_gap_minutes": params.contact_gap_minutes},
                   "A1": {s.msisdn: oracle.a1_profile(visible)[s.msisdn] for s in subjects}, "A2": a2, "A5": a5, "A6": a6, "A7": a7, "A8": a8, "A9": a9, "A10": a10, "A11": a11, "A13": a13},
        "layout_assumptions": sorted({json.dumps(a, sort_keys=True) for r in renders.values() for a in r.assumptions}),
        "defects": {name: r.defects for name, r in sorted(renders.items()) if r.defects},
        "expected_quarantine": [], "expected_merge": [],
    }
    key["layout_assumptions"] = [json.loads(a) for a in key["layout_assumptions"]]
    key["expected_quarantine"] = [{"export": name, "data_row": d["data_row"], "reason": d["reason"], "uid": d["uid"]}
                                  for name, items in sorted(key["defects"].items()) for d in items if d["status"] == "quarantined"]
    key["expected_merge"] = [{"export": name, "data_row": d["data_row"], "duplicate_of": d["duplicate_of"]}
                             for name, items in sorted(key["defects"].items()) for d in items if d["duplicate_of"]]
    return world, renders, key


def write_case(params, out_dir, registry=None):
    world, renders, key = build_case(params, registry)
    root = os.path.join(out_dir, "case-%d" % params.seed)
    if os.path.isdir(root):
        shutil.rmtree(root)
    os.makedirs(os.path.join(root, "files"))
    os.makedirs(os.path.join(root, "key"))
    for entry in key["subjects"]:
        rendered = renders[entry["person"]]
        path = rendered.write(os.path.join(root, "files"), "export-%s-%s" % (entry["person"], rendered.layout_id))
        entry["file"] = "files/" + os.path.basename(path)
    for entry in key["dumps"] + key["sessions"] + key["app_usage"] + key["ip_queries"]:
        rendered = renders[entry["name"]]
        path = rendered.write(os.path.join(root, "files"), "%s-%s" % (entry["name"], rendered.layout_id))
        entry["file"] = "files/" + os.path.basename(path)
    with open(os.path.join(root, "key", "world.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(w.world_to_json(world) + "\n")
    key_text_for_id = json.dumps({k: v for k, v in key.items() if k != "case_id"}, sort_keys=True)
    key["case_id"] = "synthetic-%s" % hashlib.sha256(key_text_for_id.encode("ascii")).hexdigest()[:10]
    with open(os.path.join(root, "key", "key.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(key, sort_keys=True, indent=1, ensure_ascii=True) + "\n")
    with open(os.path.join(root, "README.txt"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(README % (w.GENERATOR_VERSION, w.SPEC_VERSION))
    files = {}
    for base, _, names in os.walk(root):
        for name in sorted(names):
            full = os.path.join(base, name)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            if rel != "manifest.json":
                files[rel] = {"sha256": sha256_file(full), "bytes": os.path.getsize(full)}
    manifest = {"case_id": key["case_id"], "seed": params.seed, "generator_version": w.GENERATOR_VERSION, "spec_version": w.SPEC_VERSION,
                "params": key["params"], "files": dict(sorted(files.items()))}
    with open(os.path.join(root, "manifest.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(manifest, sort_keys=True, indent=1) + "\n")
    return root


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write a synthetic case with planted truth.")
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--people", type=int, default=120)
    ap.add_argument("--subjects", type=int, default=12)
    ap.add_argument("--associates", type=int, default=24)
    ap.add_argument("--days", type=int, default=90)
    ap.add_argument("--events-per-person-per-day", type=float, default=4.0)
    ap.add_argument("--p2-pairs", type=int, default=5)
    ap.add_argument("--p3-pairs", type=int, default=2)
    ap.add_argument("--p6-pairs", type=int, default=2)
    args = ap.parse_args(argv)
    params = w.Params(seed=args.seed, people=args.people, subjects=args.subjects, associates=args.associates, period_days=args.days,
                      events_per_person_per_day=args.events_per_person_per_day, p2_pairs=args.p2_pairs, p3_pairs=args.p3_pairs, p6_pairs=args.p6_pairs)
    root = write_case(params, args.out)
    print("wrote", root)
    return 0


if __name__ == "__main__":
    sys.exit(main())
