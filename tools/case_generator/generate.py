#!/usr/bin/env python3
"""Write a synthetic case with planted truth (specification: docs/data/case-generator-spec.md).

    python -X utf8 tools/case_generator/generate.py --seed 1 --out CASES_DIR [--people 120] [--subjects 6] [--days 90]

Output folder  <out>/case-<seed>/ :
    manifest.json   case id, seed, versions, parameters, SHA-256 and size of every file
    files/          one export per subject, in the real container of the layout (xlsx)
    key/key.json    the answer key (plants, decoys, reference answers A1 and A2, layout assumptions)
    key/world.json  the canonical truth (people, events)
    README.txt      what this is

Every value comes from the reserved ranges. The generator never reads the real-data vault or any real file.
"""
import argparse
import hashlib
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import oracle  # noqa: E402
import render  # noqa: E402
import world as w  # noqa: E402
from ingestion.forensic_records.layout_registry import load_registry  # noqa: E402

README = """SYNTHETIC CASE - not evidence, not real data.
Every number, identifier, address and coordinate in these files comes from a reserved range (documentation addresses, the test
network code 00101, the test TAC prefix 00, the project number block 923000000000-923000099999, a fictional grid in open ocean).
Generated by tools/case_generator (version %s, specification %s). key/key.json holds the answers planted in the files.
Where a layout's meaning is still unconfirmed, key.json says which proposed meaning the files use (layout_assumptions).
"""


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_case(params, registry=None):
    """Returns (world, renders {pid: RenderedFile}, key dict)."""
    registry = registry or load_registry()
    world = w.build_world(params)
    subjects = [p for p in world.persons if p.role == "subject"]
    renders = {}
    for subject in subjects:
        layout_id = w.OPERATOR_LAYOUTS[subject.operator]
        renders[subject.pid] = render.render_subject(world, registry.get(layout_id), subject)
    visible = {s.msisdn: renders[s.pid].rows for s in subjects}
    threshold = params.resolved_hub_threshold()
    contacts = oracle.contacts_by_subject(visible)
    hubs = oracle.hub_numbers(contacts, threshold)
    by_pid = {p.pid: p for p in world.persons}
    plants = []
    for plant in world.p2:
        x, y = by_pid[plant["x"]], by_pid[plant["y"]]
        planted_shared = [{"person": s, "number": by_pid[s].msisdn, "x_count_planted": plant["counts"][s][x.pid], "y_count_planted": plant["counts"][s][y.pid]}
                          for s in plant["shared"]]
        service = next(d for d in plant["decoys"] if d["kind"] == "service_in_common")
        hub = next(d for d in plant["decoys"] if d["kind"] == "hub_in_common")
        hub_number = by_pid[hub["person"]].msisdn
        both_see_service = all(any(r["b_raw_label"] == service["number"] for r in visible[p.msisdn]) for p in (x, y))
        plants.append({
            "id": plant["id"], "type": "common_contacts", "x": {"person": x.pid, "msisdn": x.msisdn}, "y": {"person": y.pid, "msisdn": y.msisdn},
            "planted_shared": planted_shared,
            "decoys": [
                {"kind": "service_in_common", "number": service["number"], "visible_in_both_files": both_see_service, "must_be_excluded": True},
                {"kind": "hub_in_common", "number": hub_number, "subjects_in_contact": hubs.get(hub_number, 0), "hub_threshold": threshold,
                 "visible_in_both_files": hub_number in contacts[x.msisdn] and hub_number in contacts[y.msisdn], "must_be_excluded": True}]})
    planted_pair = {frozenset((p["x"]["msisdn"], p["y"]["msisdn"])): p["id"] for p in plants}
    a2 = []
    for i, x in enumerate(subjects):
        for y in subjects[i + 1:]:
            answer = oracle.a2_common(visible, x.msisdn, y.msisdn, threshold)
            answer["plant"] = planted_pair.get(frozenset((x.msisdn, y.msisdn)))
            a2.append(answer)
    key = {
        "case_id": None, "seed": params.seed, "generator_version": w.GENERATOR_VERSION, "spec_version": w.SPEC_VERSION,
        "clock": {"local_zone": w.LOCAL_ZONE, "utc_offset_hours": w.LOCAL_UTC_OFFSET_HOURS, "key_time": "local wall clock as the files show it"},
        "params": json.loads(json.dumps(params.__dict__)),
        "subjects": [{"person": s.pid, "msisdn": s.msisdn, "operator": w.OPERATOR_LABELS[s.operator], "layout_id": renders[s.pid].layout_id,
                      "file": None, "rows": len(renders[s.pid].rows), "events_not_representable": len(renders[s.pid].skipped)} for s in subjects],
        "structure": world.structure,
        "plants": plants,
        "oracle": {"parameters": {"hub_threshold": threshold, "contact_kinds": list(oracle.PERSON_KINDS)},
                   "A1": {s.msisdn: oracle.a1_profile(visible)[s.msisdn] for s in subjects}, "A2": a2},
        "layout_assumptions": sorted({json.dumps(a, sort_keys=True) for r in renders.values() for a in r.assumptions}),
        "expected_quarantine": [], "expected_merge": [],
    }
    key["layout_assumptions"] = [json.loads(a) for a in key["layout_assumptions"]]
    return world, renders, key


def write_case(params, out_dir, registry=None):
    world, renders, key = build_case(params, registry)
    root = os.path.join(out_dir, "case-%d" % params.seed)
    if os.path.isdir(root):
        shutil.rmtree(root)
    os.makedirs(os.path.join(root, "files"))
    os.makedirs(os.path.join(root, "key"))
    for entry in key["subjects"]:
        rendered = renders[entry["person"]]
        path = rendered.write(os.path.join(root, "files"), "export-%s-%s" % (entry["person"], rendered.layout_id))
        entry["file"] = "files/" + os.path.basename(path)
    with open(os.path.join(root, "key", "world.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(w.world_to_json(world) + "\n")
    key_text_for_id = json.dumps({k: v for k, v in key.items() if k != "case_id"}, sort_keys=True)
    key["case_id"] = "synthetic-%s" % hashlib.sha256(key_text_for_id.encode("ascii")).hexdigest()[:10]
    with open(os.path.join(root, "key", "key.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(key, sort_keys=True, indent=1, ensure_ascii=True) + "\n")
    with open(os.path.join(root, "README.txt"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(README % (w.GENERATOR_VERSION, w.SPEC_VERSION))
    files = {}
    for base, _, names in os.walk(root):
        for name in sorted(names):
            full = os.path.join(base, name)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            if rel != "manifest.json":
                files[rel] = {"sha256": sha256_file(full), "bytes": os.path.getsize(full)}
    manifest = {"case_id": key["case_id"], "seed": params.seed, "generator_version": w.GENERATOR_VERSION, "spec_version": w.SPEC_VERSION,
                "params": key["params"], "files": dict(sorted(files.items()))}
    with open(os.path.join(root, "manifest.json"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(manifest, sort_keys=True, indent=1) + "\n")
    return root


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write a synthetic case with planted truth.")
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--people", type=int, default=120)
    ap.add_argument("--subjects", type=int, default=6)
    ap.add_argument("--associates", type=int, default=24)
    ap.add_argument("--days", type=int, default=90)
    ap.add_argument("--events-per-person-per-day", type=float, default=4.0)
    ap.add_argument("--p2-pairs", type=int, default=5)
    args = ap.parse_args(argv)
    params = w.Params(seed=args.seed, people=args.people, subjects=args.subjects, associates=args.associates, period_days=args.days,
                      events_per_person_per_day=args.events_per_person_per_day, p2_pairs=args.p2_pairs)
    root = write_case(params, args.out)
    print("wrote", root)
    return 0


if __name__ == "__main__":
    sys.exit(main())
