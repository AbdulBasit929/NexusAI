import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.dirname(here)
const sourcePath = path.join(here, 'tokens.json')
const cssPath = path.join(root, 'src', 'styles', 'tokens.generated.css')
const reportPath = path.join(here, 'tokens.generated.json')
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))

const themeSelectors = {
  'a-light': ':root[data-direction="a"], :root[data-direction="a"][data-theme="light"], [data-foundation-direction="a"][data-theme-preview="light"]',
  'a-dark': ':root[data-direction="a"][data-theme="dark"], [data-foundation-direction="a"][data-theme-preview="dark"]',
  'b-light': ':root, :root[data-theme="light"], :root[data-direction="b"], :root[data-direction="b"][data-theme="light"], [data-foundation-direction="b"][data-theme-preview="light"]',
  'b-dark': ':root[data-theme="dark"], :root[data-direction="b"][data-theme="dark"], [data-foundation-direction="b"][data-theme-preview="dark"]',
  'high-contrast': ':root[data-theme="high-contrast"], [data-theme-preview="high-contrast"]',
}

function walk(node, segments = [], out = new Map()) {
  if (!node || typeof node !== 'object') return out
  if ('$value' in node) {
    if (!node.$type) throw new Error(`Token ${segments.join('.')} has no $type`)
    out.set(segments.join('.'), node)
    return out
  }
  for (const [key, value] of Object.entries(node)) {
    if (!key.startsWith('$')) walk(value, [...segments, key], out)
  }
  return out
}

const tokens = walk(source)

function resolveToken(name, stack = []) {
  if (stack.includes(name)) throw new Error(`Circular token alias: ${[...stack, name].join(' -> ')}`)
  const token = tokens.get(name)
  if (!token) throw new Error(`Unknown token alias: ${name}`)
  const value = token.$value
  if (typeof value === 'string') {
    const match = value.match(/^\{([^}]+)\}$/)
    if (match) return resolveToken(match[1], [...stack, name])
  }
  return { type: token.$type, value }
}

function linearToSrgb(value) {
  return value <= 0.0031308 ? 12.92 * value : 1.055 * value ** (1 / 2.4) - 0.055
}

function oklchToRgb([L, C, hue]) {
  const radians = hue * Math.PI / 180
  const a = C * Math.cos(radians)
  const b = C * Math.sin(radians)
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b
  const s_ = L - 0.0894841775 * a - 1.291485548 * b
  const l = l_ ** 3
  const m = m_ ** 3
  const s = s_ ** 3
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map(linearToSrgb).map(value => Math.min(1, Math.max(0, value)))
  return rgb
}

function hexByte(value) {
  return Math.round(value * 255).toString(16).padStart(2, '0')
}

function colorToHex(value) {
  if (value.colorSpace !== 'oklch') throw new Error(`Unsupported colour space: ${value.colorSpace}`)
  return `#${oklchToRgb(value.components).map(hexByte).join('')}`
}

function cssValue(resolved) {
  const { type, value } = resolved
  if (type === 'color') {
    const hex = colorToHex(value)
    return value.alpha === undefined || value.alpha === 1
      ? hex
      : `rgb(${oklchToRgb(value.components).map(channel => Math.round(channel * 255)).join(' ')} / ${value.alpha})`
  }
  if (type === 'dimension' || type === 'duration') return `${value.value}${value.unit}`
  if (type === 'fontFamily') return value.map(item => item.includes(' ') ? `'${item}'` : item).join(', ')
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`
  if (type === 'shadow') {
    const channel = oklchToRgb(value.color.components).map(item => Math.round(item * 255)).join(' ')
    const alpha = value.color.alpha ?? 1
    const dimension = item => `${item.value}${item.unit}`
    return `${dimension(value.offsetX)} ${dimension(value.offsetY)} ${dimension(value.blur)} ${dimension(value.spread)} rgb(${channel} / ${alpha})`
  }
  if (type === 'fontWeight' || type === 'number') return String(value)
  throw new Error(`Unsupported token type: ${type}`)
}

function relativeLuminance(hex) {
  const channels = hex.match(/[a-f\d]{2}/gi).map(value => Number.parseInt(value, 16) / 255)
    .map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]
}

function contrast(a, b) {
  const [lighter, darker] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x)
  return (lighter + 0.05) / (darker + 0.05)
}

const globalTokens = [...tokens.keys()].filter(name => name.startsWith('global.'))
const globalLines = globalTokens.map(name => `  --nx-${name.slice(7).replaceAll('.', '-')}: ${cssValue(resolveToken(name))};`)
const css = [
  '/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit. */',
  '@layer tokens {',
  ':root {',
  '  color-scheme: light dark;',
  ...globalLines,
  '  --nx-row-height: var(--nx-density-default-row-height);',
  '  --nx-control-height: var(--nx-density-default-control-height);',
  '  --nx-card-padding: var(--nx-density-default-card-padding);',
  '}',
  ':root[data-density="compact"], [data-density-preview="compact"] {',
  '  --nx-row-height: var(--nx-density-compact-row-height);',
  '  --nx-control-height: var(--nx-density-compact-control-height);',
  '  --nx-card-padding: var(--nx-density-compact-card-padding);',
  '}',
  ':root[data-density="comfortable"], [data-density-preview="comfortable"] {',
  '  --nx-row-height: var(--nx-density-comfortable-row-height);',
  '  --nx-control-height: var(--nx-density-comfortable-control-height);',
  '  --nx-card-padding: var(--nx-density-comfortable-card-padding);',
  '}',
]

const report = { source: 'design/tokens.json', themes: {}, contrastPairs: [] }

for (const [theme, selector] of Object.entries(themeSelectors)) {
  const prefix = `themes.${theme}.`
  const primitiveNames = [...tokens.keys()].filter(name => name.startsWith(`${prefix}primitive.`))
  const semanticNames = [...tokens.keys()].filter(name => name.startsWith(`${prefix}semantic.`))
  const resolved = {}
  const lines = []
  for (const name of [...primitiveNames, ...semanticNames]) {
    const short = name.slice(prefix.length)
    const cssName = short.startsWith('semantic.') ? short.slice(9) : short.replaceAll('.', '-')
    const value = cssValue(resolveToken(name))
    lines.push(`  --nx-${cssName}: ${value};`)
    if (short.startsWith('semantic.')) resolved[cssName] = value
  }
  report.themes[theme] = resolved
  css.push(`${selector} {`, `  color-scheme: ${theme === 'high-contrast' ? 'dark' : theme.endsWith('dark') ? 'dark' : 'light'};`, ...lines, '}')

  const pairs = [
    ...['surface-0','surface-1','surface-2','surface-3','surface-ask'].flatMap(bg => [
      ['text-1', bg, 4.5, 'text'], ['text-2', bg, 4.5, 'text'], ['focus-ring', bg, 3, 'focus'],
    ]),
    ['text-3','surface-1',4.5,'text'], ['text-3','surface-2',4.5,'text'],
    ['text-on-accent','accent',4.5,'text'], ['accent-text','surface-1',4.5,'text'],
    ['border-default','surface-1',3,'ui'], ['border-strong','surface-1',3,'ui'],
    ...['ready','processing','failed','excluded','info'].map(name => [`status-${name}`,`status-${name}-surface`,4.5,'status']),
    ...Array.from({ length: 6 }, (_, index) => [`data-${index + 1}`,'surface-1',3,'chart']),
  ]
  for (const [foreground, background, required, kind] of pairs) {
    const ratio = contrast(resolved[foreground], resolved[background])
    report.contrastPairs.push({ theme, foreground, background, kind, ratio: Number(ratio.toFixed(3)), required, pass: ratio >= required })
  }
}

css.push(
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]):not([data-theme="high-contrast"]):not([data-direction="a"]) {',
  ...Object.entries(report.themes['b-dark']).map(([name, value]) => `    --nx-${name}: ${value};`),
  '    color-scheme: dark;',
  '  }',
  '  :root[data-direction="a"]:not([data-theme="light"]):not([data-theme="high-contrast"]) {',
  ...Object.entries(report.themes['a-dark']).map(([name, value]) => `    --nx-${name}: ${value};`),
  '    color-scheme: dark;',
  '  }',
  '}',
  '@media (prefers-contrast: more) {',
  '  :root:not([data-theme]) {',
  '    --nx-border-subtle: var(--nx-border-default);',
  '    --nx-text-3: var(--nx-text-2);',
  '  }',
  '}',
  '@media (forced-colors: active) {',
  '  :root {',
  '    --nx-surface-0: Canvas;',
  '    --nx-surface-1: Canvas;',
  '    --nx-surface-2: Canvas;',
  '    --nx-surface-3: Canvas;',
  '    --nx-surface-ask: Canvas;',
  '    --nx-text-1: CanvasText;',
  '    --nx-text-2: CanvasText;',
  '    --nx-text-3: CanvasText;',
  '    --nx-border-subtle: CanvasText;',
  '    --nx-border-default: CanvasText;',
  '    --nx-border-strong: CanvasText;',
  '    --nx-accent: Highlight;',
  '    --nx-text-on-accent: HighlightText;',
  '    --nx-focus-ring: Highlight;',
  '  }',
  '}',
  '}',
)

const failures = report.contrastPairs.filter(pair => !pair.pass)
report.summary = { checked: report.contrastPairs.length, passed: report.contrastPairs.length - failures.length, failed: failures.length }
fs.writeFileSync(cssPath, `${css.join('\n')}\n`)
fs.writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`)

if (failures.length) {
  console.error(`${failures.length} contrast pairs failed:`)
  for (const item of failures) console.error(`${item.theme}: ${item.foreground} / ${item.background} = ${item.ratio}:1 (needs ${item.required}:1)`)
  process.exitCode = 1
} else {
  console.log(`Generated ${path.relative(root, cssPath)} and ${path.relative(root, reportPath)}; ${report.summary.checked} contrast pairs pass.`)
}
